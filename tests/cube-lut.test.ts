import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";
import {
  parseCubeLUT,
  createIdentityCubeLUT,
  sampleCubeLUTTrilinear,
  evaluateLookColorTransform,
  serializeLookToCubeLUT,
  resolveLutUrl,
} from "../src/lib/imaging/looks/cube-lut";
import { BUILTIN_LOOKS, getLookById } from "../src/lib/imaging/looks/presets";
import { calculateDeltaE, srgbToLinear } from "../src/lib/imaging/looks/math";

describe("3D .cube LUT Parser, First-Party Generation & Trilinear Evaluation", () => {
  it("generates and verifies clean first-party .cube LUT files in public/luts", () => {
    const lutsDir = path.join(process.cwd(), "public", "luts");
    fs.mkdirSync(lutsDir, { recursive: true });

    // Remove any legacy third-party .cube files
    const expectedFiles = new Set(
      BUILTIN_LOOKS.filter((l) => Boolean(l.lutUrl)).map((l) => path.basename(l.lutUrl!))
    );
    for (const existing of fs.readdirSync(lutsDir)) {
      if (existing.endsWith(".cube") && !expectedFiles.has(existing)) {
        fs.unlinkSync(path.join(lutsDir, existing));
      }
    }

    // Generate clean first-party .cube files for all LUT-backed presets
    for (const look of BUILTIN_LOOKS) {
      if (!look.lutUrl) continue;
      const fileName = path.basename(look.lutUrl);
      const targetPath = path.join(lutsDir, fileName);
      const content = serializeLookToCubeLUT(look, 17, look.name);
      fs.writeFileSync(targetPath, content, "utf8");

      const raw = fs.readFileSync(targetPath, "utf8");
      expect(raw).toContain("Generated by Disposable Cam Look Engine v2 (First-Party Color Science)");
      expect(raw).not.toContain("REPLACES AgX");
      expect(raw).not.toContain("Dazz Cam");

      const parsed = parseCubeLUT(raw);
      expect(parsed.size).toBe(17);
      expect(parsed.title).toBe(look.name);
      expect(parsed.floatData.length).toBe(17 * 17 * 17 * 3);
      expect(parsed.byteData.length).toBe(17 * 17 * 17 * 3);
    }
  });

  it("parses identity .cube LUT and evaluates exact identity across color space", () => {
    const identity = createIdentityCubeLUT(17);
    const samples: [number, number, number][] = [
      [0, 0, 0],
      [1, 1, 1],
      [0.5, 0.5, 0.5],
      [0.25, 0.75, 0.125],
      [0.82, 0.64, 0.51],
    ];

    for (const [r, g, b] of samples) {
      const [outR, outG, outB] = sampleCubeLUTTrilinear(identity, r, g, b, 1.0);
      expect(outR).toBeCloseTo(r, 4);
      expect(outG).toBeCloseTo(g, 4);
      expect(outB).toBeCloseTo(b, 4);
    }
  });

  it("matches baked 3D .cube LUT trilinear output against reference color equation within tolerance", () => {
    const testLooks = BUILTIN_LOOKS.filter((l) => Boolean(l.lutUrl));
    const testPatches: [number, number, number][] = [
      [0.0, 0.0, 0.0], // Black
      [1.0, 1.0, 1.0], // White
      [0.5, 0.5, 0.5], // Mid-gray
      [0.78, 0.58, 0.46], // Warm skin tone
      [0.25, 0.52, 0.28], // Foliage green
      [0.22, 0.48, 0.82], // Sky blue
      [0.85, 0.25, 0.20], // Crimson red
      [0.92, 0.88, 0.84], // Wedding dress ivory highlight
    ];

    for (const look of testLooks) {
      const cubeText = serializeLookToCubeLUT(look, 17, look.name);
      const parsed = parseCubeLUT(cubeText);

      for (const [r, g, b] of testPatches) {
        const ref = evaluateLookColorTransform(r, g, b, look);
        const lutOut = sampleCubeLUTTrilinear(parsed, r, g, b, 1.0);

        const dE = calculateDeltaE(
          [srgbToLinear(ref[0]), srgbToLinear(ref[1]), srgbToLinear(ref[2])],
          [srgbToLinear(lutOut[0]), srgbToLinear(lutOut[1]), srgbToLinear(lutOut[2])]
        );

        // 17^3 trilinear interpolation matches continuous analytical curve within 0.02 OKLab deltaE
        expect(dE).toBeLessThan(0.02);
      }
    }
  });

  it("resolves legacy LUT URLs and preset IDs cleanly for backward compatibility", () => {
    expect(resolveLutUrl("/luts/dazz-cpm35.cube")).toBe("/luts/rangefinder-35.cube");
    expect(resolveLutUrl("/luts/kodak-portra-400.cube")).toBe("/luts/warm-portrait-400.cube");
    expect(getLookById("dazz-cpm35.cube").id).toBe("cpm-35");
    expect(getLookById("rangefinder-35").id).toBe("cpm-35");
    expect(getLookById("warm-portrait-400").id).toBe("portra-400");
    expect(getLookById("custom-wedding.cube").lutUrl).toBe("/luts/custom-wedding.cube");
    expect(getLookById("custom-wedding.cube").lutStrength).toBe(1.0);
  });
});
